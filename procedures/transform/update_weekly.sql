    receiving_yards_after_catch,
    receiving_first_downs,
    receiving_epa,
    receiving_2pt_conversions,
    target_share,
    air_yards_share,
    special_teams_tds,
    fantasy_points,
    fantasy_points_ppr
FROM
    raw.weekly
WHERE
    season_type = 'REG'
    AND position_group IN ('QB', 'WR', 'RB', 'TE', 'K') 
ON CONFLICT (player_id, season, week) DO NOTHING;

INSERT INTO
    players.weekly_regular_season_stats (
        player_id,
        player_name,
        player_display_name,
        position_group,
        season,
        week,
        completions,
        attempts,
        passing_yards,
        passing_tds,
        interceptions,
        sacks,
        sack_yards,
        sack_fumbles,
        sack_fumbles_lost,
        passing_air_yards,
        passing_yards_after_catch,
