CREATE TABLE IF NOT EXISTS players.weekly_regular_season_stats (
    player_id VARCHAR(50),
    player_name VARCHAR(255),
    player_display_name VARCHAR(255),
    position_group VARCHAR(10),
    season INT,
    week INT,
    completions INT,
    attempts INT,
    passing_yards FLOAT,
    passing_tds INT,
    interceptions INT,
    sacks INT,
    sack_yards FLOAT,
    sack_fumbles INT,
    sack_fumbles_lost INT,
    passing_air_yards FLOAT,
    passing_yards_after_catch FLOAT,
    passing_first_downs INT,
    passing_epa FLOAT,
    passing_2pt_conversions INT,
    carries INT,
    rushing_yards FLOAT,
    rushing_tds INT,
    rushing_fumbles INT,
    rushing_fumbles_lost INT,
    rushing_first_downs INT,
    rushing_epa FLOAT,
    rushing_2pt_conversions INT,
    receptions INT,
    targets INT,
    receiving_yards FLOAT,
    receiving_tds INT,
    receiving_fumbles INT,
    receiving_fumbles_lost INT,
    receiving_air_yards FLOAT,
    receiving_yards_after_catch FLOAT,
    receiving_first_downs INT,
    receiving_epa FLOAT,
    receiving_2pt_conversions INT,
    target_share FLOAT,
    air_yards_share FLOAT,
    special_teams_tds INT,
    fantasy_points FLOAT,
    fantasy_points_ppr FLOAT,
    PRIMARY KEY (player_id, season, week)
);

